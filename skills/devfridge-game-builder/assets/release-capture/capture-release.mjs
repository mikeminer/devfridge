#!/usr/bin/env node
/** Optional project/CI runner. Use only where that runtime permits Playwright. */
import fs from 'node:fs/promises';
import path from 'node:path';
import { pathToFileURL, fileURLToPath } from 'node:url';
import { createRequire } from 'node:module';
import { promisify } from 'node:util';
import { execFile } from 'node:child_process';
import crypto from 'node:crypto';
import { runCapture, sha256, validateProfile } from './scenario-runner.mjs';
import { createAdbDriver } from './adb-capture.mjs';
const exec = promisify(execFile);

function safeUrl(value, origin) {
  const url = new URL(value);
  if (url.username || url.password || url.search || url.hash || !['https:', 'http:'].includes(url.protocol) || (url.protocol === 'http:' && !['localhost', '127.0.0.1', '[::1]'].includes(url.hostname)) || (origin && url.origin !== origin)) throw new Error('Use an owner-approved HTTPS origin (or local development) without credentials, queries or redirects');
  return url;
}

export function validateBrowserManifest(manifest, profile) {
  const entry = safeUrl(profile.url);
  if (manifest.buildId !== profile.buildId || manifest.entrypoint !== entry.href || !Array.isArray(manifest.files) || !manifest.files.length || manifest.files.length > 500) throw new Error('Browser candidate must pin its exact same-origin entrypoint and every runtime resource');
  const urls = new Set(), hashes = new Set();
  for (const file of manifest.files) {
    const url = safeUrl(file.url, entry.origin).href;
    if (file.url !== url || urls.has(url) || !/^[a-f0-9]{64}$/.test(file.sha256) || hashes.has(file.sha256) || !/^[a-z0-9.+-]+\/[a-z0-9.+-]+$/.test(file.contentType)) throw new Error('Candidate resources need unique canonical URLs, unique SHA-256 values and explicit MIME types');
    urls.add(url); hashes.add(file.sha256);
  }
  if (!manifest.files.some(file => file.url === entry.href && file.contentType === 'text/html')) throw new Error('Candidate entrypoint HTML is missing');
  return manifest;
}

export async function fetchPinnedAssets(manifest, request) {
  const pinned = new Map(); let total = 0;
  for (const file of manifest.files) {
    const response = await request.get(file.url, { maxRedirects: 0, timeout: 15000 });
    if (response.status() !== 200 || Number(response.headers()['content-length'] || 0) > 64000000) throw new Error('Candidate file unavailable or oversized');
    const bytes = await response.body(); total += bytes.length;
    if (bytes.length > 64000000 || total > 256000000 || sha256(bytes) !== file.sha256) throw new Error('Served asset does not match the exact browser candidate');
    pinned.set(file.url, { ...file, bytes });
  }
  return pinned;
}

export async function fulfillPinnedRequest(route, pinned, faults) {
  const request = route.request(), file = pinned.get(request.url());
  if (!file || request.method() !== 'GET') {
    faults.push('Unlisted runtime resource or non-read-only network request');
    return route.abort('blockedbyclient');
  }
  const headers = { 'cache-control': 'no-store', 'x-content-type-options': 'nosniff' };
  // No network sockets, service workers or remote frames can escape the pinned capture.
  // Inline scripts/data generated by the reviewed HTML/JS remain part of that candidate.
  if (file.contentType === 'text/html') headers['content-security-policy'] = "connect-src 'self'; worker-src 'none'; frame-src 'none'; object-src 'none'; base-uri 'self'";
  await route.fulfill({ status: 200, contentType: file.contentType, headers, body: file.bytes });
}

export async function createBrowserDriver({ profile, artifact, playwrightModule }) {
  const require = createRequire(path.join(process.cwd(), 'package.json'));
  const imported = await import(playwrightModule ? pathToFileURL(path.resolve(playwrightModule)).href : pathToFileURL(require.resolve('playwright')).href);
  const playwright = imported.default || imported;
  const url = safeUrl(profile.url);
  const manifest = validateBrowserManifest(JSON.parse(artifact.toString('utf8')), profile);
  const browser = await playwright.chromium.launch({ headless: false });
  try {
    const viewport = profile.viewport;
    if (!viewport || ![viewport.width, viewport.height].every(value => Number.isInteger(value) && value >= 320 && value <= 3840) || ![1, 2, 3].includes(viewport.deviceScaleFactor)) throw new Error('Choose explicit viewport dimensions and device scale');
    const context = await browser.newContext({ viewport: { width: viewport.width, height: viewport.height }, deviceScaleFactor: viewport.deviceScaleFactor, hasTouch: true, serviceWorkers: 'block' });
    const pinned = await fetchPinnedAssets(manifest, context.request), faults = [];
    // Routing disables the HTTP cache; every loaded response is the exact reviewed byte buffer.
    await context.route('**/*', route => fulfillPinnedRequest(route, pinned, faults));
    if (typeof context.routeWebSocket !== 'function') throw new Error('This collector requires Playwright with routeWebSocket support');
    await context.routeWebSocket('**/*', socket => { faults.push('WebSocket requested during pinned static capture'); socket.close(); });
    const page = await context.newPage();
    await page.goto(url.href, { waitUntil: 'domcontentloaded', timeout: 30000 });
    if (new URL(page.url()).origin !== url.origin) throw new Error('Unexpected application redirect');
    await page.bringToFront();
    const hook = async method => page.evaluate(name => {
      const api = globalThis.__releaseCapture;
      if (!api || typeof api[name] !== 'function') throw new Error('Missing game-owned release evidence hook');
      return api[name]();
    }, method);
    const driver = {
      fixture: false, inputSource: 'browser-input', now: () => performance.now(), wallNow: () => Date.now(), sleep: ms => new Promise(resolve => setTimeout(resolve, ms)),
      identity: () => hook('identity'),
      readState: async () => {
        if (faults.length) throw new Error('Runtime escaped the pinned candidate resource manifest');
        const state = await hook('readState');
        const visibility = await page.evaluate(() => ({ visibility: document.visibilityState, foreground: document.hasFocus() }));
        return { ...state, ...visibility };
      },
      startRecording: () => hook('startRecording'), stopRecording: async () => { const telemetry = await hook('stopRecording'); return { ...telemetry, faults: [...(telemetry.faults || []), ...faults] }; },
      device: async () => {
        const identity = await hook('identity');
        const observed = await page.evaluate(() => ({ model: navigator.userAgent, os: navigator.platform, hardwareConcurrency: navigator.hardwareConcurrency }));
        return { ...observed, class: 'desktop-browser', physical: false, collection: 'browser-runtime', browser: browser.version(), renderer: identity.renderer, observationId: crypto.randomUUID(), emulatedViewport: viewport, resourceBinding: 'pinned-response-bytes', swipeInput: 'desktop-mouse-drag' };
      },
      input: async action => {
        if (action.kind === 'click') await page.locator(action.selector).click({ timeout: 5000 });
        else if (action.kind === 'key') await page.keyboard.press(action.key, { delay: action.holdMs || 0 });
        else if (action.kind === 'tap') await page.touchscreen.tap(action.x, action.y);
        else if (action.kind === 'swipe') { await page.mouse.move(action.x, action.y); await page.mouse.down(); await page.mouse.move(action.toX, action.toY, { steps: 12 }); await page.mouse.up(); }
      },
      screenshot: () => page.screenshot({ type: 'png', fullPage: false, animations: 'allow' }),
      close: () => browser.close(),
    };
    return driver;
  } catch (error) { await browser.close(); throw error; }
}

export async function composeCapturedSet(directory, profile, profileDirectory, python = process.platform === 'win32' ? 'python' : 'python3') {
  const options = profile.captions;
  if (!options || options.fontApproved !== true || !options.font || !options.fontLicense || !['1080x1920', '1920x1080'].includes(options.size)) throw new Error('Caption composition requires an approved font, licence and output orientation');
  const font = path.resolve(profileDirectory, options.font), license = path.resolve(profileDirectory, options.fontLicense);
  await fs.access(font); const licenseBytes = await fs.readFile(license);
  const script = fileURLToPath(new URL('../store-compose.py', import.meta.url));
  await exec(python, [script, path.join(directory, 'captions.json'), '--out-dir', path.join(directory, 'store-assets'), '--font', font, '--size', options.size, '--band-height', String(options.bandHeight || 240), '--check-set'], { timeout: 120000, maxBuffer: 1024 * 1024, env: { ...process.env, PYTHONDONTWRITEBYTECODE: '1' } });
  await fs.writeFile(path.join(directory, 'store-assets/FONT-LICENSE.txt'), licenseBytes, { flag: 'wx' });
  const entries = JSON.parse(await fs.readFile(path.join(directory, 'captions.json'), 'utf8'));
  const files = [];
  for (const entry of entries) { const bytes = await fs.readFile(path.join(directory, 'store-assets', entry.output)); files.push({ filename: entry.output, bytes: bytes.length, sha256: sha256(bytes) }); }
  return { status: 'validated', tool: 'store-compose.py', files, fontLicenseSha256: sha256(licenseBytes), layout: 'Full capture contained without cropping; added caption band' };
}

async function main(argv) {
  if (!argv.length || argv.includes('--help')) { console.log('Usage: node capture-release.mjs --profile profile.json --artifact candidate.apk|browser-build-manifest.json --out NEW_DIRECTORY [--adb adb] [--serial SERIAL] [--checklist checks.json] [--thermal thermal.json] [--python python3] [--playwright-module local/module.mjs]\nRequires the real game evidence hook. No ready state means no screenshot; no evidence means release remains blocked.'); return; }
  const args = Object.fromEntries(Array.from({ length: Math.ceil(argv.length / 2) }, (_, i) => [argv[i * 2], argv[i * 2 + 1]]));
  let driver;
  try {
    const profileFile = path.resolve(args['--profile']);
    const profileBytes = await fs.readFile(profileFile), profile = JSON.parse(profileBytes);
    validateProfile(profile);
    const artifact = await fs.readFile(args['--artifact']);
    const artifactSha256 = sha256(artifact);
    const readOptional = async file => file ? JSON.parse(await fs.readFile(file, 'utf8')) : {};
    driver = profile.platform === 'seeker' ? await createAdbDriver({ profile, artifactSha256, adb: args['--adb'] || 'adb', serial: args['--serial'] }) : await createBrowserDriver({ profile, artifact, playwrightModule: args['--playwright-module'] });
    const result = await runCapture({ profile, profileBytes, artifactSha256, driver, outDir: args['--out'], checklist: await readOptional(args['--checklist']), thermal: await readOptional(args['--thermal']), compose: directory => composeCapturedSet(directory, profile, path.dirname(profileFile), args['--python']) });
    console.log(JSON.stringify({ captures: result.captures.length, performance: result.performanceAssessment.status, storeAssets: result.composed.status, humanVisualReview: result.humanVisualReview }));
    process.exitCode = result.performanceAssessment.releaseReady ? 0 : 1;
  } catch (error) { console.error('Capture blocked: ' + String(error.message).replace(/https?:\/\/\S+/g, '[URL redacted]')); process.exitCode = 1; }
  finally { if (driver) await driver.close(); }
}
if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) await main(process.argv.slice(2));
