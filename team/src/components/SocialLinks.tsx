type Props = {
  socials: Socials;
};

export function SocialLinks({ socials }: Props) {
  const entries = SOCIALS.filter(({ key }) => socials[key]);
  if (entries.length === 0) return null;

  return (
    <div className="member-socials">
      {entries.map(({ key, icon, url, prefix }) => {
        const handle = socials[key]!;
        const href = url(handle);
        const display = `${prefix}${handle}`;

        return href ? (
          <a
            key={key}
            className="social-link"
            href={href}
            target="_blank"
            rel="noopener noreferrer"
          >
            {icon}
            <span>{display}</span>
          </a>
        ) : (
          <span key={key} className="social-link social-nolink">
            {icon}
            <span>{display}</span>
          </span>
        );
      })}
    </div>
  );
}
